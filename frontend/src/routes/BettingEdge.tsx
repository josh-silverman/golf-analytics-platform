// ---------------------------------------------------------------------------
// Formatting helpers
// ---------------------------------------------------------------------------

function formatPct(p: number, decimals = 1): string {
  return `${(p * 100).toFixed(decimals)}%`
}

function formatEdge(edge: number): string {
  const pct = (edge * 100).toFixed(1)
  return edge >= 0 ? `+${pct}%` : `${pct}%`
}

function formatAmerican(odds: number): string {
  return odds >= 0 ? `+${odds}` : `${odds}`
}

// ---------------------------------------------------------------------------
// Price provenance
// ---------------------------------------------------------------------------

// Whether this line was priced against a real sportsbook consensus. Anything
// else was generated by the backend from the served probability itself
// (`_generate_mock_american_odds`: model_prob + sin(field_position) + vig), so
// its "edge" is an artifact of field position and carries no information.
//
// This is a PER-LINE property. The board also carries a single `odds_source`,
// but that reads "datagolf" when *any* one line was real, so it cannot be used
// to describe a row or a market.
//
// A line without a real price is now dropped from the view entirely rather than
// shown with blanked columns: with no market price there is no disagreement to
// display, and a row of dashes only invites the reader to wonder what was
// withheld.
function isRealPrice(line: BettingLine): boolean {
  return line.odds_source === 'datagolf'
}

// Real-price coverage across a market, for the reliability note. Computed from
// the unfiltered board so it describes the market rather than the current view.
function priceCoverage(lines: BettingLine[]): { real: number; total: number } {
  return { real: lines.filter(isRealPrice).length, total: lines.length }
}

// Minimum model-probability filter options for the table. Default is ≥10% so the
// view immediately surfaces meaningful divergences instead of longshot noise,
// while "All" restores the full list.
const PROB_THRESHOLDS: { label: string; value: number }[] = [
  { label: 'All', value: 0 },
  { label: '≥10%', value: 0.1 },
  { label: '≥20%', value: 0.2 },
  { label: '≥30%', value: 0.3 },
]

// ---------------------------------------------------------------------------
// Edge bar chart (custom SVG visualisation)
//
// Renders a horizontal diverging bar chart: positive edge extends right
// (accent colour), negative edge extends left (muted red). The zero line
// sits in the centre so viewers can read both direction and magnitude at a
// glance — a standard viz used by sports-betting analytics teams.
// ---------------------------------------------------------------------------

const BAR_HEIGHT = 16
const BAR_GAP = 6
const CHART_ROW_HEIGHT = BAR_HEIGHT + BAR_GAP
const LABEL_WIDTH = 160
const AXIS_WIDTH = 300 // total half-width (left + right) of chart area
const PADDING = { top: 24, right: 16, bottom: 28, left: 8 }

function EdgeBarChart({ lines, maxEdge }: { lines: BettingLine[]; maxEdge: number }) {
  // Show at most 20 players so the chart stays readable.
  const visible = lines.slice(0, 20)
  const scale = maxEdge > 0 ? (AXIS_WIDTH / 2) / maxEdge : 1

  const svgWidth = LABEL_WIDTH + AXIS_WIDTH + PADDING.left + PADDING.right
  const svgHeight = PADDING.top + visible.length * CHART_ROW_HEIGHT + PADDING.bottom

  const zeroX = PADDING.left + LABEL_WIDTH + AXIS_WIDTH / 2

  return (
    <svg
      width={svgWidth}
      height={svgHeight}
      aria-label="Edge bar chart"
      className="select-none overflow-visible font-mono text-xs"
    >
      {/* zero axis */}
      <line
        x1={zeroX}
        y1={PADDING.top - 8}
        x2={zeroX}
        y2={PADDING.top + visible.length * CHART_ROW_HEIGHT}
        stroke="#232B40"
        strokeWidth={1}
      />

      {/* axis labels */}
      <text
        x={zeroX - AXIS_WIDTH / 2}
        y={PADDING.top - 10}
        textAnchor="middle"
        className="fill-fg-tertiary text-[10px]"
      >
        −{formatEdge(maxEdge).replace('+', '')}
      </text>
      <text x={zeroX} y={PADDING.top - 10} textAnchor="middle" className="fill-fg-tertiary text-[10px]">
        0%
      </text>
      <text
        x={zeroX + AXIS_WIDTH / 2}
        y={PADDING.top - 10}
        textAnchor="middle"
        className="fill-fg-tertiary text-[10px]"
      >
        {formatEdge(maxEdge)}
      </text>

      {visible.map((line, i) => {
        const y = PADDING.top + i * CHART_ROW_HEIGHT
        const barWidth = Math.abs(line.edge) * scale
        // Direction only: the board reads above the market, or below it. Bar
        // colour and weight carry no ranking beyond that — brightening a subset
        // as "actionable" is the recommendation this page no longer makes.
        const above = line.edge >= 0.005
        const fill = above ? '#34A65F' : '#EF4444'
        const opacity = above ? 0.85 : 0.45

        return (
          <g key={line.player_id}>
            {/* player label */}
            <text
              x={PADDING.left + LABEL_WIDTH - 8}
              y={y + BAR_HEIGHT / 2 + 4}
              textAnchor="end"
              className="fill-fg text-[11px]"
            >
              {line.player_name.length > 22
                ? line.player_name.slice(0, 21) + '…'
                : line.player_name}
            </text>

            {/* bar */}
            <rect
              x={above ? zeroX : zeroX - barWidth}
              y={y}
              width={Math.max(barWidth, 2)}
              height={BAR_HEIGHT}
              rx={2}
              fill={fill}
              opacity={opacity}
            />

            {/* edge value label */}
            <text
              x={above ? zeroX + barWidth + 4 : zeroX - barWidth - 4}
              y={y + BAR_HEIGHT / 2 + 4}
              textAnchor={above ? 'start' : 'end'}
              className={`fill-fg-secondary text-[10px]`}
            >
              {formatEdge(line.edge)}
            </text>
          </g>
        )
      })}

      {/* bottom axis ticks */}
      {[-1, -0.5, 0, 0.5, 1].map((frac) => {
        const x = zeroX + frac * (AXIS_WIDTH / 2)
        return (
          <line
            key={frac}
            x1={x}
            y1={PADDING.top + visible.length * CHART_ROW_HEIGHT}
            x2={x}
            y2={PADDING.top + visible.length * CHART_ROW_HEIGHT + 4}
            stroke="#232B40"
            strokeWidth={1}
          />
        )
      })}
    </svg>
  )
}

// ---------------------------------------------------------------------------
// Market selector
// ---------------------------------------------------------------------------

function MarketPicker({
  value,
  onChange,
}: {
  value: OutcomeKey
  onChange: (k: OutcomeKey) => void
}) {
  return (
    <div className="flex flex-wrap gap-2">
      {OUTCOME_KEYS.map((key) => (
        <button
          key={key}
          onClick={() => onChange(key)}
          className={`rounded-full px-3 py-1 text-xs font-medium transition-colors ${
            key === value
              ? 'bg-accent text-white'
              : 'border bg-surface text-fg-secondary hover:text-fg'
          }`}
        >
          {OUTCOME_LABELS[key]}
        </button>
      ))}
    </div>
  )
}

// ---------------------------------------------------------------------------
// Minimum model-probability filter
// ---------------------------------------------------------------------------

function ProbabilityFilter({
  value,
  onChange,
}: {
  value: number
  onChange: (v: number) => void
}) {
  return (
    <div className="flex flex-wrap gap-2">
      {PROB_THRESHOLDS.map((t) => (
        <button
          key={t.value}
          onClick={() => onChange(t.value)}
          className={`rounded-full px-3 py-1 text-xs font-medium transition-colors ${
            t.value === value
              ? 'bg-accent text-white'
              : 'border bg-surface text-fg-secondary hover:text-fg'
          }`}
        >
          {t.label}
        </button>
      ))}
    </div>
  )
}

